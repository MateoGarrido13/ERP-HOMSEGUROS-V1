CREATE TABLE IF NOT EXISTS productor (
    id INTEGER NOT NULL,
    -- Matricula oficial SSN: solo digitos, sin separadores (ver FORMATO_NRO_MATRICULA.md).
    matricula_ssn VARCHAR(8) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_productor_matricula_ssn UNIQUE (matricula_ssn),
    CONSTRAINT fk_productor_usuario
        FOREIGN KEY (id) REFERENCES usuario (id)
        ON DELETE CASCADE
        ON UPDATE CASCADE,
    CONSTRAINT chk_productor_matricula_ssn CHECK (
        matricula_ssn ~ '^[0-9]+$'
        AND length(matricula_ssn) BETWEEN 3 AND 8
    )
);

CREATE TABLE IF NOT EXISTS asegurado (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_productor INTEGER NOT NULL,
    nombre VARCHAR(255) NOT NULL,
    apellido VARCHAR(255) NOT NULL, -- o "Razon social"
    email VARCHAR(255) NOT NULL,
    tipo_documento_sigla VARCHAR(16) NOT NULL DEFAULT 'DNI',
    numero_documento VARCHAR(32) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (id),
    CONSTRAINT fk_asegurado_productor
        FOREIGN KEY (id_productor) REFERENCES productor (id)
        ON DELETE RESTRICT
        ON UPDATE CASCADE,
    CONSTRAINT fk_asegurado_tipo_documento
        FOREIGN KEY (tipo_documento_sigla) REFERENCES tipos_documento (sigla)
        ON DELETE RESTRICT
        ON UPDATE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_asegurado_productor ON asegurado (id_productor);

