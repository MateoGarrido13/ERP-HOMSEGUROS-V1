CREATE OR REPLACE FUNCTION endoso_fecha_no_excede_poliza()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM poliza p
        WHERE p.id = NEW.id_poliza
          AND NEW.fecha_emision > p.fecha_fin
    ) THEN
        RAISE EXCEPTION 'endoso.fecha_emision no puede exceder poliza.fecha_fin';
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_endoso_fecha_no_excede_poliza ON endoso;
CREATE TRIGGER trg_endoso_fecha_no_excede_poliza
BEFORE INSERT OR UPDATE OF id_poliza, fecha_emision ON endoso
FOR EACH ROW
EXECUTE FUNCTION endoso_fecha_no_excede_poliza();

