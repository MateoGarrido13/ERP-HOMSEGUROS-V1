-- Copia literal de sql/schema/schema.sql al momento de levantar Supabase local
-- (2026-11-13). No reconcilia todavia `usuario` con Supabase Auth (auth.users):
-- usuario.id sigue INTEGER y usuario.password sigue existiendo. Esa reconciliacion
-- es PA-8 de docs/specs/EPICA-acceso/spec.md y se hace en una migracion aparte.
-- Si sql/schema/schema.sql cambia, este archivo no se edita a mano: se agrega
-- una migracion nueva con el diff (asi lo versiona supabase db diff).
--
-- Esquema en PostgreSQL.
-- Los CHECK se aplican siempre: no dependen de una version del motor.
--
-- Herencia por clave primaria compartida:
--   usuario <- productor
-- El asegurado (cliente de cartera) no opera el ERP: no es usuario ni tiene contrasena.
-- La matricula es solo del productor (PAS); un asegurado no la tiene ni la hereda.
-- Una misma persona fisica puede ser productor y, ademas, asegurado en otra cartera
-- (u otra fila de asegurado): coinciden documento y datos de contacto, pero son
-- entidades distintas (usuario+productor frente a asegurado).
-- El productor puede figurar como asegurado en su propia cartera: mismo DNI,
-- dos tuplas; solo la fila productor lleva matricula.
--   poliza  <- poliza_hogar, poliza_automotor, poliza_consorcio, poliza_comercio
--
-- Cada asegurado tiene un unico productor.
-- Cada poliza tiene un unico asegurado; el productor se obtiene por ese asegurado.
-- Toda poliza tiene fecha_inicio (emision) y fecha_fin (renovar el acuerdo, no el pago).
-- Se fijan al cargar la poliza o en sus renovaciones. vigente no anula fecha_fin:
-- baja solo pone vigente = false; fecha_fin ya estaba.
-- Pagos: poliza.fecha_prox_pago. PENDIENTES alerta contra esa fecha.
-- Resolver el aviso registra un endoso con fecha_emision <= poliza.fecha_fin.
-- Ese INSERT actualiza fecha_prox_pago; si pagado = true, se corre X dias.
-- X no es 30 fijo: depende de poliza.cuotas (cuotas con las que se registro el acuerdo).
-- Un bien de hogar no tiene vigencia propia.
-- El inmueble es una entidad. Hogar, consorcio y comercio lo referencian
-- (tablas independientes). El mismo inmueble puede usarse en otra poliza.
-- El vehiculo depende de su poliza de automotor.
-- Una poliza de automotor cubre un unico vehiculo.
-- La clave de vehiculo es la de poliza_automotor.
--
-- numero_poliza no es unico global (ver POLIZA_UNICA.md). La identidad del ERP
-- es poliza.id; el numero literal de la compania es atributo de negocio.
-- Rama = poliza.tipo CHAR(2): HO hogar, AU automotor, CO consorcio, CC comercio.
-- Unicidad legal: aseguradora + tipo + numero.
-- Una poliza (poliza.id) tiene muchos endosos; el contrato legal no se duplica por endoso.
-- Un endoso exige poliza previa y completa (FK id_poliza; todos los atributos).
-- Puede colgar de una poliza no vigente: deudor moroso dado de baja que termina
-- el saldo pendiente. El alta (CU-16) inserta poliza vigente completa y luego
-- el primer endoso, misma transaccion.
--
-- El tipo es un discriminador CHAR(2). La FK compuesta (id, tipo)
-- amarra cada extension a HO, AU, CO o CC y evita mezclar ramos,
-- tambien ante UPDATEs concurrentes. No hay triggers de exclusion.
--
-- Dinero: NUMERIC(15, 2) en la moneda de la poliza (ISO 4217, default ARS).
-- El valor de cada vehiculo cubierto y endoso.importe usan esa misma moneda.
--
-- Visibilidad. La aplicacion abre la transaccion del productor con:
--   SET LOCAL app.acceso = 'productor';
--   SET LOCAL app.productor_id = '<id del productor>';
-- y la de la red (directivo o administrativo) con:
--   SET LOCAL app.acceso = 'admin';
-- Sin una de esas dos, las politicas no devuelven filas ni aceptan escrituras.
-- El productor solo lee sus asegurados (tabla asegurado / vista cliente),
-- sus polizas y el riesgo asociado. No escribe.

CREATE TABLE IF NOT EXISTS usuario (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(255) NOT NULL,
    apellido VARCHAR(255) NOT NULL, -- o "Razon social"
    email VARCHAR(255) NOT NULL,
    dni INTEGER NOT NULL,
    password VARCHAR(255) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (id),
    CONSTRAINT uk_usuario_email UNIQUE (email)
);

