CREATE TABLE IF NOT EXISTS poliza (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    numero_poliza VARCHAR(255) NOT NULL,
    id_aseguradora INTEGER NOT NULL,
    id_asegurado INTEGER NOT NULL,
    tipo CHAR(2) NOT NULL,
    valor_poliza NUMERIC(15, 2) NOT NULL,
    moneda VARCHAR(3) NOT NULL DEFAULT 'ARS',
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NOT NULL,
    fecha_prox_pago DATE NOT NULL,
    cuotas INTEGER NOT NULL,
    vigente BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (id),
    CONSTRAINT uk_poliza_id_tipo UNIQUE (id, tipo),
    CONSTRAINT uk_poliza_legal UNIQUE (id_aseguradora, tipo, numero_poliza),
    CONSTRAINT fk_poliza_aseguradora
        FOREIGN KEY (id_aseguradora) REFERENCES aseguradora (id)
        ON DELETE RESTRICT
        ON UPDATE CASCADE,
    CONSTRAINT fk_poliza_asegurado
        FOREIGN KEY (id_asegurado) REFERENCES asegurado (id)
        ON DELETE RESTRICT
        ON UPDATE CASCADE,
    CONSTRAINT chk_poliza_valor CHECK (valor_poliza > 0),
    CONSTRAINT chk_poliza_moneda CHECK (moneda ~ '^[A-Z]{3}$'),
    CONSTRAINT chk_poliza_vigencia CHECK (fecha_fin >= fecha_inicio),
    CONSTRAINT chk_poliza_cuotas CHECK (cuotas > 0),
    CONSTRAINT chk_poliza_tipo CHECK (tipo IN ('HO', 'AU', 'CO', 'CC'))
);

