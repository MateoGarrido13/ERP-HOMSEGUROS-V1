-- Un vehiculo por poliza: su clave primaria es la de poliza_automotor.
-- valor es la suma asegurada de ese vehiculo, en poliza.moneda.
CREATE TABLE IF NOT EXISTS vehiculo (
    id INTEGER NOT NULL,
    patente VARCHAR(7) NOT NULL, -- vieja: 6 (AAA111); nueva: 7 (AA111AA)
    tipo CHAR(1) NOT NULL, -- n: nueva, v: vieja
    marca VARCHAR(255) NOT NULL,
    modelo VARCHAR(255) NOT NULL,
    anio INTEGER NOT NULL,
    valor NUMERIC(15, 2) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_vehiculo_poliza
        FOREIGN KEY (id) REFERENCES poliza_automotor (id)
        ON DELETE CASCADE
        ON UPDATE CASCADE,
    CONSTRAINT chk_vehiculo_anio CHECK (anio BETWEEN 1900 AND 2100),
    CONSTRAINT chk_vehiculo_tipo CHECK (
        (tipo = 'v' AND length(patente) = 6)
        OR (tipo = 'n' AND length(patente) = 7)
    ),
    CONSTRAINT chk_vehiculo_valor CHECK (valor > 0)
);

-- PostgreSQL no actualiza updated_at solo.
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$;

