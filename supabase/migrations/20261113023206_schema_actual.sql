CREATE OR REPLACE FUNCTION sesion_es_admin()
RETURNS boolean
LANGUAGE sql
STABLE
AS $$
    SELECT COALESCE(current_setting('app.acceso', true), '') = 'admin'
$$;

CREATE OR REPLACE FUNCTION sesion_es_productor()
RETURNS boolean
LANGUAGE sql
STABLE
AS $$
    SELECT COALESCE(current_setting('app.acceso', true), '') = 'productor'
$$;

CREATE OR REPLACE FUNCTION current_productor_id()
RETURNS integer
LANGUAGE plpgsql
STABLE
AS $$
DECLARE
    raw text;
BEGIN
    raw := current_setting('app.productor_id', true);
    IF raw IS NULL OR btrim(raw) = '' THEN
        RETURN NULL;
    END IF;
    RETURN btrim(raw)::integer;
EXCEPTION
    WHEN invalid_text_representation THEN
        RETURN NULL;
END;
$$;

