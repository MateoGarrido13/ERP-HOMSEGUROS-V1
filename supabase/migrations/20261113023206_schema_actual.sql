-- Endosos del mismo contrato (poliza.id). N endosos : 1 poliza.
-- Historial append-only: cada emision es INSERT; filas anteriores no se actualizan.
-- No hay endoso huerfano ni sobre poliza incompleta.
-- Excepcion de vigencia: endoso permitido si vigente=false (mora / saldo tras baja).
-- El alta de poliza vigente completa inserta el primer endoso; no hay poliza sin esa fila.
-- fecha_emision no excede poliza.fecha_fin (aviso de pago resuelto).
-- metodo_pago: A debito automatico, T tarjeta, E efectivo/transferencia.
-- pagado: true ya pago; false aun no pago.
-- pagado = true corre poliza.fecha_prox_pago X dias (X segun poliza.cuotas, no 30 fijo).
CREATE TABLE IF NOT EXISTS endoso (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_poliza INTEGER NOT NULL,
    numero_endoso VARCHAR(255) NOT NULL,
    fecha_emision DATE NOT NULL,
    importe NUMERIC(15, 2) NOT NULL,
    metodo_pago CHAR(1) NOT NULL,
    pagado BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (id),
    CONSTRAINT uk_endoso_poliza_numero UNIQUE (id_poliza, numero_endoso),
    CONSTRAINT fk_endoso_poliza
        FOREIGN KEY (id_poliza) REFERENCES poliza (id)
        ON DELETE CASCADE
        ON UPDATE CASCADE,
    CONSTRAINT chk_endoso_metodo_pago CHECK (metodo_pago IN ('A', 'T', 'E'))
);

CREATE INDEX IF NOT EXISTS idx_endoso_poliza ON endoso (id_poliza);

